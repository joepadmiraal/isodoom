namespace IsoDoom.Tools.SyntheticIwad;

/// <summary>
/// A small synthetic IWAD for running the WAD viewer check in CI (T1.6b),
/// where no id Software WAD is available. Everything in it is generated here
/// (procedural palettes, patterns and shapes), so it holds no id data and can
/// be built anywhere; the output is deterministic.
/// <para>
/// It identifies as shareware Doom (<c>E1M1</c>, no <c>E3M1</c>) and has at
/// least one lump of every <see cref="LumpKind"/>: <c>PLAYPAL</c> (14
/// palettes) and <c>COLORMAP</c> (34 maps); <c>PNAMES</c>, <c>TEXTURE1</c> and
/// <c>TEXTURE2</c> with a single-patch, a multi-patch (overlapping, clipped
/// at the edges), a masked and a non-128-high texture; wall patches in
/// <c>P_START</c>/<c>P1_START</c> with a duplicate name (the later copy wins,
/// the earlier one is overridden); flats in <c>F_START</c>/<c>F1_START</c>;
/// sprites in <c>S_START</c> with a fully rotated frame (mirrored pairs) and
/// rotation-0 frames (one full bright in its spawn state, one for a thing
/// hanging from the ceiling), plus a sprite lump no sprite uses; global graphics
/// (title, status bar, menu, font glyphs, with offsets and transparency); a
/// map with a real BSP tree and every wall-section case (see <c>BuildMap</c>), and
/// <c>E1M2</c>, the specials map M5's tasks add their cases to (see
/// <c>BuildSpecialsMap</c>; a switch texture pair); ENDOOM, GENMIDI, DMXGUS, MUS and MIDI music, DMX and PC
/// speaker sounds, a demo and a plain text lump.
/// </para>
/// </summary>
public static class SyntheticIwad
{
    public const string DefaultFileName = "isodoom-synthetic.wad";

    /// <summary>The IWAD's bytes.</summary>
    public static byte[] Build()
    {
        var w = new Writer();
        w.Lump("PLAYPAL", BuildPlaypal());
        w.Lump("COLORMAP", BuildColormap());
        w.Lump("ENDOOM", BuildEndoom());
        w.Lump("DEMO1", BuildDemo());
        BuildMap(w);
        BuildSpecialsMap(w);
        w.Lump("TEXTURE1", BuildTextureLump(
            new Tex("NULLTEX", 64, 64, false, (0, 0, 0)), // texture 0 is never drawn (vanilla's AASTINKY/AASHITTY)
            new Tex("BRICK1", 64, 64, false, (0, 0, 0)),
            new Tex("BRKPNL", 128, 128, false, (0, 0, 0), (64, 0, 1), (-32, 64, 0), (32, 64, 0), (96, 64, 0)),
            new Tex("GRATE", 64, 64, true, (0, 0, 2), (32, 0, 2)),
            new Tex("PANEL", 64, 72, false, (0, -8, 1))));
        w.Lump("TEXTURE2", BuildTextureLump(
            new Tex("WINFRAME", 32, 64, false, (0, 0, 2)),
            new Tex("SW1BRCOM", 64, 128, false, (0, 0, 3)), // a switch pair of p_switch.c's list (T5.1, E1M2)
            new Tex("SW2BRCOM", 64, 128, false, (0, 0, 4)),
            // An animated wall texture of p_spec.c's animdefs, its three frames the bricks scrolled down (T5.7, E1M2).
            new Tex("SLADRIP1", 64, 64, false, (0, -64, 0), (0, 0, 0)),
            new Tex("SLADRIP2", 64, 64, false, (0, -48, 0), (0, 16, 0)),
            new Tex("SLADRIP3", 64, 64, false, (0, -32, 0), (0, 32, 0))));
        w.Lump("PNAMES", BuildPNames("WALLBRK", "WALLPNL", "WINDOW", "SWOFF", "SWON"));
        w.Lump("GENMIDI", BuildGenmidi());
        w.Lump("DMXGUS", Encoding.ASCII.GetBytes("# Synthetic test patch map\r\n0, 2, 1, 0, acpiano\r\n"));
        w.Lump("D_E1M1", BuildMus());
        w.Lump("D_INTRO", BuildMidi());
        w.Lump("DSPISTOL", BuildDmxSound());
        w.Lump("DPPISTOL", BuildPcSpeakerSound());
        w.Lump("README", Encoding.ASCII.GetBytes(
            "IsoDoom synthetic test IWAD. Generated by tools/SyntheticIwad for the WAD viewer check in CI.\n"
            + "All content is procedural; it contains no id Software data. Not a playable game.\n"));

        // Global graphics (found by structure, as the UI lumps are).
        w.Lump("TITLEPIC", EncodePatch(TitlePic()));
        w.Lump("STBAR", EncodePatch(StatusBar()));
        w.Lump("M_DOOM", EncodePatch(MenuLogo()));
        w.Lump("STCFN065", EncodePatch(Glyph(_glyphA)));
        w.Lump("STCFN066", EncodePatch(Glyph(_glyphB)));
        w.Lump("STCFN067", EncodePatch(Glyph(_glyphC)));

        w.Markers("S_START");
        Image troo = Arrow();
        w.Lump("TROOA1", EncodePatch(troo));
        w.Lump("TROOA2A8", EncodePatch(troo.Tinted(1)));
        w.Lump("TROOA3A7", EncodePatch(troo.Tinted(2)));
        w.Lump("TROOA4A6", EncodePatch(troo.Tinted(3)));
        w.Lump("TROOA5", EncodePatch(troo.Tinted(4)));
        w.Lump("BAR1A0", EncodePatch(Barrel(0)));
        w.Lump("BAR1B0", EncodePatch(Barrel(1)));
        w.Lump("XXXXA0", EncodePatch(Barrel(2))); // in no sprite name list: listed, but no sprite frame
        w.Lump("COLUA0", EncodePatch(Lamp()));      // floor lamp (MT_MISC31): a full-bright spawn frame
        w.Lump("GOR2A0", EncodePatch(Hanging()));   // hanging body (MT_MISC56): spawns on the ceiling
        // T5.8: E1M2's keys, a blue keycard and a yellow skull key, each blinking between A and a full-bright B.
        w.Lump("BKEYA0", EncodePatch(Key(false, Index(1, 2, 3), Index(3, 4, 3))));
        w.Lump("BKEYB0", EncodePatch(Key(false, Index(3, 4, 3), Index(5, 6, 3))));
        w.Lump("YSKUA0", EncodePatch(Key(true, Index(5, 5, 0), Index(7, 7, 1))));
        w.Lump("YSKUB0", EncodePatch(Key(true, Index(7, 7, 1), Index(7, 7, 3))));
        w.Markers("S_END");

        w.Markers("P_START", "P1_START");
        w.Lump("WALLBRK", EncodePatch(Bricks()));
        w.Lump("WALLPNL", EncodePatch(Panel(0)));
        w.Lump("WINDOW", EncodePatch(Window()));
        w.Lump("WALLPNL", EncodePatch(Panel(2))); // duplicate: this one wins, the first is overridden
        w.Lump("SWOFF", EncodePatch(Switch(false)));
        w.Lump("SWON", EncodePatch(Switch(true)));
        w.Markers("P1_END", "P_END");

        w.Markers("F_START", "F1_START");
        w.Lump("FLOOR1", Checker().Pixels);
        w.Lump("FLOOR2", Diagonal().Pixels);
        w.Lump("LAVA1", Waves(0).Pixels);
        // T5.7: p_spec.c's animated flats LAVA1-LAVA4 and NUKAGE1-NUKAGE3 (animdefs; E1M1 and E1M2 draw them).
        w.Lump("LAVA2", Waves(16).Pixels);
        w.Lump("LAVA3", Waves(32).Pixels);
        w.Lump("LAVA4", Waves(48).Pixels);
        w.Lump("NUKAGE1", Ooze(0).Pixels);
        w.Lump("NUKAGE2", Ooze(1).Pixels);
        w.Lump("NUKAGE3", Ooze(2).Pixels);
        w.Lump("F_SKY1", Solid(64, 64, (x, y) => Index(1, 2, 3)).Pixels); // the sky flat (r_sky.h SKYFLATNAME)
        w.Markers("F1_END", "F_END");
        return w.Build();
    }

    /// <summary>
    /// Checks that the IWAD loads as the viewer loads it and has what the viewer
    /// check is meant to exercise. Returns the problems found (empty when fine).
    /// </summary>
    public static List<string> Check(WadArchive wad)
    {
        var problems = new List<string>();
        IwadInfo info = IwadIdentification.D_IdentifyVersion(wad);
        if (info.GameMode != GameMode.shareware)
            problems.Add($"identifies as {info.GameMode}, expected shareware");
        var catalog = GraphicsCatalog.Load(wad);
        foreach (GraphicCategory c in Enum.GetValues<GraphicCategory>())
        {
            if (catalog.Count(c) == 0)
                problems.Add($"no {c} in the graphics catalog");
        }
        var kinds = new HashSet<LumpKind>();
        bool overridden = false;
        foreach (LumpEntry e in LumpDirectory.Build(wad))
        {
            kinds.Add(e.Kind);
            overridden |= e.IsOverridden;
        }
        foreach (LumpKind k in Enum.GetValues<LumpKind>())
        {
            if (!kinds.Contains(k))
                problems.Add($"no lump of kind {LumpDirectory.KindName(k)}");
        }
        if (!overridden)
            problems.Add("no overridden lump");
        // T7.8b: the OPL bank and the MUS song read as i_oplmusic.c and mus2mid.c would.
        if (Genmidi.TryRead(wad.W_CacheLumpName("GENMIDI").Span, out string? genmidiError) is not { HasNames: true })
            problems.Add($"GENMIDI does not read: {genmidiError ?? "names missing"}");
        if (MusSong.TryRead(wad.W_CacheLumpName("D_E1M1").Span, out string? musError) is not MusSong song)
            problems.Add($"D_E1M1 does not read: {musError}");
        else if (song.Events.Count != SongEvents || song.LengthTics != SongTics || song.Mus2MidError is not null)
            problems.Add($"D_E1M1 has {song.Events.Count} events over {song.LengthTics} tics, expected {SongEvents} over {SongTics}{(song.Mus2MidError is null ? "" : $"; mus2mid.c refuses it: {song.Mus2MidError}")}");
        try
        {
            var map = Level.Load(wad, "E1M1");
            if (map.Nodes.Length < 2 || map.Sectors.Length < 2)
                problems.Add($"E1M1 has {map.Nodes.Length} nodes and {map.Sectors.Length} sectors, expected a BSP tree over several sectors");
            var walls = WallSections.Build(map, catalog.Textures);
            if (walls.Missing.Count > 0)
                problems.Add($"E1M1 has missing wall textures: {string.Join(", ", walls.Missing)}");
            foreach (WallSectionKind k in Enum.GetValues<WallSectionKind>())
            {
                if (!Has(walls, s => s.Kind == k && s.Texture != 0))
                    problems.Add($"E1M1 has no textured {k} wall section");
            }
            if (!Has(walls, s => s.Kind == WallSectionKind.Upper && (s.Line.Flags & Line.ML_DONTPEGTOP) != 0 && s.Texture != 0))
                problems.Add("E1M1 has no upper unpegged wall");
            if (!Has(walls, s => s.Kind == WallSectionKind.Lower && (s.Line.Flags & Line.ML_DONTPEGBOTTOM) != 0 && s.Texture != 0))
                problems.Add("E1M1 has no lower unpegged wall");
            if (!Has(walls, s => s.BackSector is { CeilingPic: WallSections.SKYFLATNAME } && s.FrontSector.CeilingPic == WallSections.SKYFLATNAME))
                problems.Add("E1M1 has no line with a sky ceiling on both sides");
            if (!Has(walls, s => s.BackSector is { } b && b.FloorHeight == b.CeilingHeight))
                problems.Add("E1M1 has no closed door (a two-sided line onto a sector with no height)");
        }
        catch (WadFormatException e)
        {
            problems.Add($"E1M1 does not load: {e.Message}");
        }
        try
        {
            var specials = Level.Load(wad, "E1M2");
            if (specials.Sectors.Length != SpecialsSectors || specials.Sectors[0].Lines.Count != 3 + SpecialsAlcoves)
                problems.Add($"E1M2 has {specials.Sectors.Length} sectors, its corridor {specials.Sectors[0].Lines.Count} lines; expected {SpecialsSectors} and {3 + SpecialsAlcoves}");
            if (specials.Sectors[DoorSector].Lines.Count != 4 || specials.R_PointInSubsector(144 << 16, 196 << 16).Sector.Index != DoorSector)
                problems.Add("E1M2's door sector is not between its rooms");
            if (specials.R_PointInSubsector(352 << 16, 196 << 16).Sector.Index != TeleportRoom
                || specials.R_PointInSubsector(416 << 16, 196 << 16).Sector.Index != TeleportPad
                || specials.R_PointInSubsector(TeleportDestX << 16, TeleportDestY << 16).Sector.Tag != TeleportTag
                || specials.Lines[TeleportLine].Special != 97 || specials.Lines[TeleportLine].FrontSector?.Index != TeleportRoom)
                problems.Add("E1M2's teleporter is not set up (room T, the pad, line 86, the destination in room R)");
            var walls = WallSections.Build(specials, catalog.Textures);
            if (walls.Missing.Count > 0)
                problems.Add($"E1M2 has missing wall textures: {string.Join(", ", walls.Missing)}");
            if (!Has(walls, s => s.Texture != 0 && catalog.Textures.TextureDefs[s.Texture].Name == "SW1BRCOM"))
                problems.Add("E1M2 has no switch texture");
        }
        catch (WadFormatException e)
        {
            problems.Add($"E1M2 does not load: {e.Message}");
        }
        return problems;
    }

    private static bool Has(WallSections walls, Func<WallSection, bool> match)
    {
        foreach (WallSection s in walls.Sections)
        {
            if (match(s))
                return true;
        }
        return false;
    }

    // ---- Palette ----
    // Palette 0 is a 8x8x4 RGB grid: index = r | g << 3 | b << 6 (r, g in 0..7, b in 0..3).
    // No component reaches 255, which leaves the viewer check's background colours free.

    private static int Index(int r, int g, int b) => r | g << 3 | b << 6;

    private static (int R, int G, int B) BaseColor(int i) => ((i & 7) * 36, ((i >> 3) & 7) * 36, (i >> 6) * 84);

    private static byte[] BuildPlaypal()
    {
        // 0: normal; 1-8: red (damage, berserk); 9-12: gold (pickup); 13: green (radiation suit), as st_stuff.c numbers them.
        var tints = new List<(int R, int G, int B, int Num, int Den)> { (0, 0, 0, 0, 1) };
        for (int k = 1; k <= 8; k++)
            tints.Add((255, 0, 0, k, 9));
        for (int k = 1; k <= 4; k++)
            tints.Add((215, 186, 69, k, 8));
        tints.Add((0, 255, 0, 1, 8));

        byte[] lump = new byte[Playpal.PaletteSize * tints.Count];
        for (int p = 0; p < tints.Count; p++)
        {
            (int tr, int tg, int tb, int num, int den) = tints[p];
            for (int i = 0; i < 256; i++)
            {
                (int r, int g, int b) = BaseColor(i);
                int o = p * Playpal.PaletteSize + i * 3;
                lump[o] = (byte)(r + (tr - r) * num / den);
                lump[o + 1] = (byte)(g + (tg - g) * num / den);
                lump[o + 2] = (byte)(b + (tb - b) * num / den);
            }
        }
        return lump;
    }

    private static byte[] BuildColormap()
    {
        // 0-31: darker in 32 steps; 32: inverted greyscale (invulnerability); 33: all black.
        byte[] lump = new byte[Colormap.MapSize * 34];
        for (int m = 0; m < 32; m++)
        {
            for (int i = 0; i < 256; i++)
            {
                int r = i & 7, g = (i >> 3) & 7, b = i >> 6;
                lump[m * 256 + i] = (byte)Index((r * (32 - m) + 16) / 32, (g * (32 - m) + 16) / 32, (b * (32 - m) + 16) / 32);
            }
        }
        for (int i = 0; i < 256; i++)
        {
            (int r, int g, int b) = BaseColor(i);
            int inv = 255 - (r * 3 + g * 6 + b) / 10; // 0..255
            lump[32 * 256 + i] = (byte)Index((inv * 7 + 127) / 255, (inv * 7 + 127) / 255, (inv * 3 + 127) / 255);
        }
        return lump;
    }

    // ---- Images ----

    private sealed class Image
    {
        public readonly int Width, Height, Left, Top;
        public readonly byte[] Pixels;
        public readonly bool[] Opaque;

        public Image(int width, int height, int left = 0, int top = 0)
        {
            Width = width;
            Height = height;
            Left = left;
            Top = top;
            Pixels = new byte[width * height];
            Opaque = new bool[width * height];
        }

        public void Set(int x, int y, int index)
        {
            Pixels[y * Width + x] = (byte)index;
            Opaque[y * Width + x] = true;
        }

        /// <summary>A copy with the blue level shifted by <paramref name="step"/> (wrapping), so each rotation looks different.</summary>
        public Image Tinted(int step)
        {
            var copy = new Image(Width, Height, Left, Top);
            for (int p = 0; p < Pixels.Length; p++)
            {
                if (Opaque[p])
                    copy.Set(p % Width, p / Width, (Pixels[p] & 63) | ((((Pixels[p] >> 6) + step) & 3) << 6));
            }
            return copy;
        }
    }

    private static Image Solid(int width, int height, Func<int, int, int> color, int left = 0, int top = 0)
    {
        var img = new Image(width, height, left, top);
        for (int y = 0; y < height; y++)
        {
            for (int x = 0; x < width; x++)
                img.Set(x, y, color(x, y));
        }
        return img;
    }

    private static Image Bricks() => Solid(64, 64, (x, y) =>
    {
        int row = y / 16, bx = (x + (row % 2) * 16) % 32;
        if (y % 16 == 15 || bx == 31)
            return Index(4, 4, 1); // mortar
        return Index(5 + (row + bx / 8) % 3, 1 + (y % 16) / 6, 0);
    });

    private static Image Panel(int hue) => Solid(64, 128, (x, y) =>
    {
        int edge = Math.Min(Math.Min(x, 63 - x), Math.Min(y % 64, 63 - y % 64));
        int level = edge < 2 ? 7 : edge < 4 ? 2 : 3 + (y % 64) / 22;
        return Index(level, level, hue + (edge < 2 ? 1 : 0));
    });

    /// <summary>A switch: a panel with a plate in the middle, lit when <paramref name="on"/>.</summary>
    private static Image Switch(bool on) => Solid(64, 128, (x, y) =>
    {
        bool plate = x >= 20 && x < 44 && y >= 48 && y < 80;
        if (plate)
            return on ? Index(7, 6, 0) : Index(2, 1, 0);
        return Index(3 + (x / 16 + y / 32) % 2, 3, 1);
    });

    private static Image Window()
    {
        var img = new Image(32, 64);
        for (int y = 0; y < 64; y++)
        {
            for (int x = 0; x < 32; x++)
            {
                bool frame = x < 4 || x >= 28 || y < 4 || y >= 60 || (x >= 15 && x <= 16) || (y >= 30 && y <= 33);
                if (frame)
                    img.Set(x, y, Index(1 + x % 3, 3, 2));
            }
        }
        return img;
    }

    private static Image Checker() => Solid(64, 64, (x, y) => ((x / 8 + y / 8) % 2 == 0) ? Index(6, 6, 2) : Index(2, 2, 1));

    private static Image Diagonal() => Solid(64, 64, (x, y) => Index((x + y) / 16, 7 - (x + y) / 18, (x / 16) % 4));

    private static Image Waves(int phase) => Solid(64, 64, (x, y) =>
    {
        int t = (x * 3 + Tri(y * 4) + phase) % 64;
        return Index(7, t / 10, 0);
    });

    // Green blobs that drift with the frame (T5.7's animated flat).
    private static Image Ooze(int frame) => Solid(64, 64, (x, y) =>
    {
        int t = (Tri(x * 2 + frame * 21) + Tri(y * 2 + 11)) / 8;
        return Index(t % 3, 3 + t % 5, 0);
    });

    private static int Tri(int v) => Math.Abs(v % 64 - 32); // a triangle wave in integers

    private static Image TitlePic() => Solid(320, 200, (x, y) =>
    {
        // An isometric diamond grid over a vertical gradient.
        bool line = (x + 2 * y) % 32 < 2 || (x - 2 * y + 400) % 32 < 2;
        return line ? Index(7, 6, 1) : Index(y / 40, y / 50, 3 - y / 67);
    });

    private static Image StatusBar() => Solid(320, 32, (x, y) =>
    {
        bool box = x % 64 < 2 || y < 2 || y >= 30;
        return box ? Index(6, 6, 1) : Index(3, 3, 1 + (x / 64) % 2);
    });

    private static Image MenuLogo()
    {
        // A diamond outline with a transparent inside and outside, offsets as menu graphics have.
        var img = new Image(96, 40, -4, -2);
        for (int y = 0; y < 40; y++)
        {
            for (int x = 0; x < 96; x++)
            {
                int d = Math.Abs(x - 48) * 40 / 96 + Math.Abs(y - 20);
                if (d >= 14 && d <= 20)
                    img.Set(x, y, Index(7, d - 13, 0));
            }
        }
        return img;
    }

    private static readonly string[] _glyphA = ["..#..", ".#.#.", "#...#", "#####", "#...#", "#...#", "#...#"];
    private static readonly string[] _glyphB = ["####.", "#...#", "####.", "#...#", "#...#", "#...#", "####."];
    private static readonly string[] _glyphC = [".###.", "#...#", "#....", "#....", "#....", "#...#", ".###."];

    private static Image Glyph(string[] rows)
    {
        var img = new Image(rows[0].Length, rows.Length);
        for (int y = 0; y < rows.Length; y++)
        {
            for (int x = 0; x < rows[y].Length; x++)
            {
                if (rows[y][x] == '#')
                    img.Set(x, y, Index(7, 7 - y / 2, 0));
            }
        }
        return img;
    }

    private static Image Arrow()
    {
        // Asymmetric (points right, notch at the top), so a mirrored rotation is visibly mirrored. A foot
        // (rows 44-55) reaches 4 rows below the origin, as many of id's sprites do (T3.5).
        var img = new Image(41, 56, 20, 52);
        for (int y = 0; y < 56; y++)
        {
            for (int x = 0; x < 41; x++)
            {
                bool head = x >= 20 && Math.Abs(y - 28) <= 40 - x;
                bool shaft = x < 20 && y >= 22 && y <= 34;
                bool notch = y < 6 && x > 26;
                bool foot = y >= 44 && x >= 12 && x <= 24 + (y - 44) / 3;
                if ((head || shaft || foot) && !notch)
                    img.Set(x, y, Index(x / 6, 2 + y / 14, 1));
            }
        }
        return img;
    }

    private static Image Lamp()
    {
        // A post with a bright bulb; 3 rows below the origin.
        var img = new Image(15, 48, 7, 45);
        for (int y = 0; y < 48; y++)
        {
            for (int x = 0; x < 15; x++)
            {
                bool bulb = y < 12 && (x - 7) * (x - 7) + (y - 6) * (y - 6) <= 36;
                bool post = y >= 12 && Math.Abs(x - 7) <= (y >= 44 ? 6 : 2);
                if (bulb || post)
                    img.Set(x, y, bulb ? Index(7, 6 + (x + y) % 2, 1) : Index(2 + y % 3, 2, 2));
            }
        }
        return img;
    }

    private static Image Hanging()
    {
        // A rope and a hanging shape, asymmetric; its origin is near the bottom, as id's hanging sprites.
        var img = new Image(20, 60, 9, 58);
        for (int y = 0; y < 60; y++)
        {
            for (int x = 0; x < 20; x++)
            {
                bool rope = y < 20 && x >= 8 && x <= 10;
                bool body = y >= 20 && Math.Abs(x - 9) <= 3 + (y - 20) / 8 && !(y > 50 && x < 6);
                if (rope || body)
                    img.Set(x, y, rope ? Index(5, 5, 0) : Index(6, (x + 2 * y) % 4, 0));
            }
        }
        return img;
    }

    /// <summary>A key (T5.8): a card (a rectangle with a stripe) or a skull key (a round head on a shaft).</summary>
    private static Image Key(bool skull, int body, int detail)
    {
        var img = new Image(10, 14, 5, 12);
        for (int y = 0; y < 14; y++)
        {
            for (int x = 0; x < 10; x++)
            {
                bool part, mark;
                if (skull)
                {
                    part = (y < 7 && (x - 5) * (x - 5) + (y - 3) * (y - 3) <= 12) || (y >= 7 && Math.Abs(x - 5) <= 1) || (y >= 11 && x >= 5 && x <= 8);
                    mark = y == 3 && (x == 3 || x == 7);
                }
                else
                {
                    part = x >= 1 && x <= 8 && y >= 2;
