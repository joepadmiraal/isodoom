        void Event(int type, int channel, params byte[] data)
        {
            last = score.Count;
            score.Add((byte)((type << 4) | channel));
            score.AddRange(data);
        }
        void Wait(int tics)
        {
            score[last] |= 0x80; // the group's last event: a delay follows
            if (tics >= 128)
                score.Add((byte)(0x80 | (tics >> 7)));
            score.Add((byte)(tics & 0x7F));
        }
        const int Release = 0, Press = 1, Pitch = 2, SystemEvent = 3, Controller = 4, ScoreEnd = 6, Drums = MusSong.PercussionChannel;

        Event(Controller, 0, 0, 33);  // bass: instrument 33
        Event(Controller, 0, 3, 110); // volume
        Event(Controller, 0, 4, 40);  // pan, left of the centre
        Event(Controller, 1, 0, 80);  // lead: instrument 80
        Event(Controller, 1, 3, 100);
        Event(Controller, 1, 4, 88);
        Event(Controller, 2, 0, 3);   // chords: instrument 3, a two-voice one
        Event(Controller, 2, 5, 90);  // expression
        Event(Controller, Drums, 3, 120);
        int[] roots = [36, 36, 41, 43];
        int[] arpeggio = [0, 4, 7, 12];
        for (int step = 0; step < 16; step++)
        {
            int root = roots[step / 4];
            int lead = root + 24 + arpeggio[step % 4];
            int drum = step % 4 == 2 ? 38 : step % 2 == 0 ? 35 : 42;
            if (step % 4 == 0)
            {
                Event(Press, 0, (byte)(0x80 | root), (byte)(90 + step)); // bass, with a volume
                Event(Press, 2, (byte)(0x80 | (root + 16)), 70);         // chord's third
            }
            if (step % 2 == 0)
                Event(Press, 1, (byte)(0x80 | lead), 110);
            else
                Event(Press, 1, (byte)lead); // no volume: the channel's last
            Event(Press, Drums, (byte)(0x80 | drum), (byte)(step % 4 == 0 ? 127 : 80));
            Wait(30);
            Event(Release, 1, (byte)lead);
            Event(Release, Drums, (byte)drum);
            if (step % 4 == 3)
            {
                Event(Release, 0, (byte)root);
                Event(Release, 2, (byte)(root + 16));
            }
            Wait(5);
        }
        // A long lead note bent up and back, released, all notes off, the score end.
        Event(Press, 1, 0x80 | 72, 100);
        Wait(20);
        Event(Pitch, 1, 160);
        Wait(20);
        Event(Pitch, 1, 192);
        Wait(20);
        Event(Pitch, 1, 128);
        Wait(20);
        Event(Release, 1, "H"u8.ToArray());
        Wait(200); // two delay bytes
        Event(SystemEvent, 1, 11); // all notes off
        Wait(35);
        Event(ScoreEnd, 0);

        ushort[] instruments = [3, 33, 80, 135, 138, 142]; // the programs, and the drums as percussion note + 100
        int start = MusSong.HeaderSize + 2 * instruments.Length;
        byte[] lump = new byte[start + score.Count];
        Encoding.ASCII.GetBytes("MUS\x1A", lump);
        BinaryPrimitives.WriteUInt16LittleEndian(lump.AsSpan(4), (ushort)score.Count);
        BinaryPrimitives.WriteUInt16LittleEndian(lump.AsSpan(6), (ushort)start);
        BinaryPrimitives.WriteUInt16LittleEndian(lump.AsSpan(8), 3); // primary channels
        BinaryPrimitives.WriteUInt16LittleEndian(lump.AsSpan(12), (ushort)instruments.Length);
        for (int i = 0; i < instruments.Length; i++)
            BinaryPrimitives.WriteUInt16LittleEndian(lump.AsSpan(MusSong.HeaderSize + 2 * i), instruments[i]);
        score.CopyTo(lump, start);
        return lump;
    }

    // D_INTRO: a type 1 MIDI file (Chocolate Doom plays a PWAD's MIDI lumps
    // through midifile.c, T7.8d): a tempo track changing the tempo mid-song,
    // a melodic track (program changes, volume, pan, pitch bends, running
    // status, a note on of velocity 0 as its note off, a SysEx and a text
    // event) and a percussion track (channel 10; one note outside GENMIDI's
    // 35-81), 96 ticks per quarter note.
    private static byte[] BuildMidi()
    {
        static void Vlq(List<byte> b, int v)
        {
            var groups = new List<byte> { (byte)(v & 0x7F) };
            while ((v >>= 7) != 0)
                groups.Insert(0, (byte)(0x80 | (v & 0x7F)));
            b.AddRange(groups);
        }
        static void Ev(List<byte> b, int delta, params byte[] bytes)
        {
            Vlq(b, delta);
            b.AddRange(bytes);
        }

        var tempo = new List<byte>();
        Ev(tempo, 0, 0xFF, 0x51, 3, 0x07, 0xA1, 0x20);    // 500000 us per beat
        Ev(tempo, 384, 0xFF, 0x51, 3, 0x06, 0x1A, 0x80);  // 400000
        Ev(tempo, 384, 0xFF, 0x51, 3, 0x09, 0x27, 0xC0);  // 600000
        Ev(tempo, 384, 0xFF, 0x2F, 0);

        var melody = new List<byte>();
        Ev(melody, 0, 0xFF, 0x01, 4, (byte)'t', (byte)'e', (byte)'s', (byte)'t');
        Ev(melody, 0, 0xC0, 19);                 // program 20
        Ev(melody, 0, 0xB0, 0x07, 100);          // volume
        Ev(melody, 0, 0x0A, 20);                 // pan (running status)
        Ev(melody, 0, 0xC1, 6);
        Ev(melody, 0, 0xB1, 0x0A, 110);
        int[] scale = [60, 62, 64, 65, 67, 69, 71, 72];
        for (int i = 0; i < scale.Length; i++)
        {
            Ev(melody, i == 0 ? 0 : 48, 0x90, (byte)scale[i], (byte)(70 + 7 * i));
            Ev(melody, 0, 0x91, (byte)(scale[i] - 12), 90);
            if (i == 3)
                Ev(melody, 24, 0xE0, 0x00, 0x50);     // bend up
            if (i == 4)
                Ev(melody, 24, 0xE0, 0x00, 0x40);     // and back
            if (i == 5)
                Ev(melody, 0, 0xF0, 3, 0x7E, 0x7F, 0xF7); // SysEx
            if (i == 6)
                Ev(melody, 0, 0xB0, 0x0A, 64);       // pan centre
            Ev(melody, i is 3 or 4 ? 24 : 48, 0x90, (byte)scale[i], 0);  // velocity 0: off
            Ev(melody, 0, 0x81, (byte)(scale[i] - 12), 0);
        }
        Ev(melody, 0, 0xB1, 0x7B, 0);            // all notes off
        Ev(melody, 0, 0xFF, 0x2F, 0);

        var drums = new List<byte>();
        byte[] kit = [36, 42, 38, 42, 30, 42, 38, 81];
        for (int i = 0; i < 16; i++)
        {
            Ev(drums, i == 0 ? 0 : 36, 0x99, kit[i % kit.Length], 110);
            Ev(drums, 36, 0x89, kit[i % kit.Length], 0);
        }
        Ev(drums, 0, 0xFF, 0x2F, 0);

        var midi = new List<byte>();
        midi.AddRange(Encoding.ASCII.GetBytes("MThd"));
        midi.AddRange([0, 0, 0, 6, 0, 1, 0, 3, 0, 96]); // format 1, 3 tracks, 96 ticks per quarter
        foreach (List<byte> track in new[] { tempo, melody, drums })
        {
            midi.AddRange(Encoding.ASCII.GetBytes("MTrk"));
            midi.AddRange([0, 0, (byte)(track.Count >> 8), (byte)track.Count]);
            midi.AddRange(track);
        }
        return [.. midi];
    }

    private static byte[] BuildDmxSound()
    {
        // DMX: format 3, 11025 Hz, sample count (incl. the 16 pad bytes either side), then 8-bit unsigned samples.
        const int Samples = 2048;
        byte[] lump = new byte[8 + 16 + Samples + 16];
        BinaryPrimitives.WriteUInt16LittleEndian(lump, 3);
        BinaryPrimitives.WriteUInt16LittleEndian(lump.AsSpan(2), 11025);
        BinaryPrimitives.WriteUInt32LittleEndian(lump.AsSpan(4), Samples + 32);
        for (int i = 0; i < 16; i++)
        {
            lump[8 + i] = 128;
            lump[8 + 16 + Samples + i] = 128;
        }
        for (int i = 0; i < Samples; i++)
        {
            int amplitude = 100 * (Samples - i) / Samples;
            lump[8 + 16 + i] = (byte)(128 + ((i / 12) % 2 == 0 ? amplitude : -amplitude)); // decaying square wave
        }
        return lump;
    }

    private static byte[] BuildPcSpeakerSound()
    {
        // PC speaker: format 0, tone count, then one tone byte per 1/140 s.
        byte[] lump = new byte[4 + 20];
        BinaryPrimitives.WriteUInt16LittleEndian(lump.AsSpan(2), 20);
        for (int i = 0; i < 20; i++)
            lump[4 + i] = (byte)(60 - i * 2);
        return lump;
    }

    // ---- WAD writer ----

    private sealed class Writer
    {
        private readonly List<(string Name, byte[] Data)> _lumps = [];

        public void Lump(string name, byte[]? data = null) => _lumps.Add((name, data ?? []));

        public void Markers(params string[] names)
        {
            foreach (string name in names)
                Lump(name);
        }

        /// <summary>Header, lump data, then the directory (as id's tools lay it out).</summary>
        public byte[] Build()
        {
            int dataSize = 0;
            foreach ((_, byte[] data) in _lumps)
                dataSize += data.Length;
            byte[] wad = new byte[12 + dataSize + 16 * _lumps.Count];
            Encoding.ASCII.GetBytes("IWAD", wad);
            BinaryPrimitives.WriteInt32LittleEndian(wad.AsSpan(4), _lumps.Count);
            BinaryPrimitives.WriteInt32LittleEndian(wad.AsSpan(8), 12 + dataSize);
            int pos = 12;
            for (int i = 0; i < _lumps.Count; i++)
            {
                (string name, byte[] data) = _lumps[i];
                if (name.Length > 8)
                    throw new InvalidOperationException($"Lump name {name} is longer than 8 characters.");
                data.CopyTo(wad, pos);
                Span<byte> entry = wad.AsSpan(12 + dataSize + 16 * i, 16);
                BinaryPrimitives.WriteInt32LittleEndian(entry, data.Length == 0 ? 0 : pos);
                BinaryPrimitives.WriteInt32LittleEndian(entry[4..], data.Length);
                Encoding.ASCII.GetBytes(name, entry[8..]);
                pos += data.Length;
            }
            return wad;
        }
    }
